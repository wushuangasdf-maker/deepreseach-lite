"""
工具使用策略提示词构建 — tools.py

为 Agent 提供工具使用的微观策略指导。
与 system.py 的分工：
  - system.py：宏观流程（角色、几轮搜索、报告结构）
  - tools.py：  微观决策（怎么搜、何时抓、如何判断信息充分）

用法:
    from agent.prompts.tools import build_tools_prompt

    # 作为系统提示词的补充段落，或单独注入
    guidance = build_tools_prompt()
    system = build_system_prompt(tools) + "\n\n" + guidance
"""


def build_tools_prompt() -> str:
    """
    构建工具使用策略提示词。

    返回:
        str: 工具使用策略字符串，可追加到系统提示词末尾。
    """
    parts: list[str] = [
        _kb_search_strategy(),
        _search_strategy(),
        _fetch_strategy(),
        _save_strategy(),
        _common_mistakes(),
    ]
    return "\n\n".join(parts)


# ── 各段落构建函数 ──────────────────────────────────────────────


def _kb_search_strategy() -> str:
    """知识库搜索策略 —— 何时优先查 KB"""
    return (
        "## 工具使用：知识库搜索\n\n"
        "### 使用时机\n"
        "- **优先于互联网搜索**：研究每个子问题时，先调用 kb_search_tool 检查私有知识库。"
        "如果返回相关内容，将其作为内部资料引用；如果返回空或不相关，再使用 web_search_tool。\n"
        "- 适合查：内部规范、产品文档、历史报告、项目架构说明、领域专有知识。\n"
        "- 不适合查：实时新闻、最新市场数据、公开行业报告、互联网热点。\n\n"
        "### 使用策略\n"
        "- 查询词应使用文档中可能出现的关键词，例如「RAG 实现方式」「API 错误处理规范」。\n"
        "- 知识库返回结果中的「相似度」分数越高，表示内容越匹配。"
        "分数 > 0.6 的结果通常可直接引用。\n"
        "- 如果知识库返回空结果或不相关内容，不要反复尝试——直接改用 web_search_tool。\n"
        "- 知识库结果和互联网搜索结果可以互补使用，共同支撑研究报告。"
    )


def _search_strategy() -> str:
    """搜索策略 —— 如何构造搜索词、如何调整搜索方向"""
    return (
        "## 工具使用：搜索\n\n"
        "### 搜索词构造原则\n"
        "1. **精准具体**：避免宽泛的单个词，用 2-5 个关键词组合。\n"
        "   差：「芯片」\n"
        "   好：「2026年 AI芯片 市场份额 英伟达 华为」\n"
        "2. **变换角度**：同一课题从不同维度搜索。\n"
        "   例如研究「新能源汽车市场」可分别搜：\n"
        "   - 「2026年 新能源汽车 销量 排名」\n"
        "   - 「新能源汽车 补贴政策 2026」\n"
        "   - 「动力电池 技术路线 固态电池 2026」\n"
        "3. **第二轮搜索要补缺口**：不要重复第一轮的搜索词。\n"
        "   如果第一轮缺数据 → 搜具体数据\n"
        "   如果第一轮缺不同观点 → 搜反面意见\n"
        "   如果第一轮信息陈旧 → 搜最新进展\n\n"
        "### 搜索结果评估\n"
        "- 优先点击标题直接相关、来源可信的结果\n"
        "- 如果搜索结果与课题无关，立即更换搜索词，不要将就使用\n"
        "- 如果连续两次搜索都无收获，标注「该方向信息不足」并转向其他角度"
    )


def _fetch_strategy() -> str:
    """抓取策略 —— 何时抓取、抓取哪些页面"""
    return (
        "## 工具使用：抓取页面\n\n"
        "### 抓取时机\n"
        "**必须抓取的情况：**\n"
        "- 搜索结果摘要信息不完整，需要查看原文才能获取关键数据\n"
        "- 需要核实某个具体数字、日期或事实\n"
        "- 摘要内容看起来权威且信息量大，值得全文阅读\n\n"
        "**不需要抓取的情况：**\n"
        "- 搜索结果摘要已包含全部所需信息\n"
        "- 来源明显不可靠（个人博客、匿名论坛、内容农场）\n"
        "- 页面标题与课题无关\n\n"
        "### 抓取数量控制\n"
        "- 每轮搜索后抓取 1-2 个最有价值的页面即可\n"
        "- 不要为了「全面」而批量抓取——这浪费时间和 token\n"
        "- 如果抓取的页面内容不理想（纯导航、付费墙、JS渲染空白页），"
        "不要反复抓取同一页面，直接更换来源"
    )


def _save_strategy() -> str:
    """保存策略 —— 保存时机和参数"""
    return (
        "## 工具使用：保存报告\n\n"
        "### 调用时机\n"
        "- **仅在报告完整撰写完毕后调用一次**\n"
        "- 不要在报告写到一半时保存——保存的是最终版本\n"
        "- 如果报告需要修改，直接修改后再保存，不要保存多个草稿版本\n\n"
        "### 参数填写\n"
        "- `title`：你自拟的报告标题，用于生成文件名。例如「2026年AI芯片市场竞争格局分析」\n"
        "- `report`：完整的 Markdown 报告正文，包含标题、各章节、参考资料\n"
        "- `output_dir`：使用默认值即可，不需要手动指定"
    )


def _common_mistakes() -> str:
    """常见错误 —— 负向约束，告诉 LLM 不要做什么"""
    return (
        "## 工具使用：常见错误（禁止）\n\n"
        "1. **搜索词过长**：不要把整个问题或整句话当搜索词。搜索引擎不是聊天机器人，"
        "用关键词而非自然语言。\n"
        "2. **重复搜索**：不要用相同或高度相似的搜索词反复搜索。每次搜索应有明确的新目的。\n"
        "3. **搜索后不抓取**：看到好的搜索结果却不抓取原文，仅凭摘要写报告。"
        "摘要信息量有限，容易出错。\n"
        "4. **抓取后不使用**：抓取了页面内容，写报告时却凭「记忆」写而不引用原文。"
        "始终从实际的抓取内容中提取信息。\n"
        "5. **过早保存**：报告尚未完成就调用 save_report_tool。"
        "保存意味着报告定稿，调用前确认报告已完整。\n"
        "6. **搜索-抓取死循环**：搜了抓、抓了搜、无限循环。记住研究速度原则——"
        "信息够用就动笔，两轮后强制自己进入撰写阶段。"
    )
